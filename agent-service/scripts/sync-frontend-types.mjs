import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../../', import.meta.url);
const modules = ['conversation', 'tools', 'mandates', 'events'];
let output = '// Generated by agent-service/scripts/sync-frontend-types.mjs. Do not edit.\n';
for (const name of modules) {
  const source = await readFile(new URL(`agent-service/contracts/${name}.ts`, root), 'utf8');
  output += source.split(/\n(?:export )?const /)[0].replace(/^import[\s\S]*?;\n/gm, '') + '\n';
}
const destination = new URL('frontend-service/shared/services/agent-service/types.ts', root);
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw new Error(
      'Run node agent-service/scripts/sync-frontend-types.mjs to refresh frontend contracts',
    );
} else await writeFile(destination, output);
